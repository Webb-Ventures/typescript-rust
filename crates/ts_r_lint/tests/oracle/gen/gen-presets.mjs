// Writes ../presets.txt: which rules each published preset turns on (`<preset> <rule>` lines).
// Data only: the presets' rule lists, read from the installed packages' configs.
//
// Usage: node gen-presets.mjs --tools <dir with node_modules: @eslint/js, typescript-eslint,
//        eslint-plugin-jsdoc, eslint-plugin-unicorn> > ../presets.txt
// Pinned as in gen-rule-oracle.mjs (@eslint/js 10, typescript-eslint 8.71.1,
// eslint-plugin-jsdoc 63.3.3, eslint-plugin-unicorn 79.0.0).

import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const i = process.argv.indexOf('--tools');
const req = createRequire(path.join(path.resolve(process.argv[i + 1]), 'package.json'));
const load = async (name) => (await import(pathToFileURL(req.resolve(name)).href)).default;
const js = req('@eslint/js');
const tse = req('typescript-eslint');
const jsdoc = await load('eslint-plugin-jsdoc');
const unicorn = await load('eslint-plugin-unicorn');
const on = (cfgs) => {
  const m = {};
  for (const c of [].concat(cfgs)) for (const [k, v] of Object.entries(c.rules ?? {})) m[k] = v;
  return Object.entries(m)
    .filter(([, v]) => {
      const s = Array.isArray(v) ? v[0] : v;
      return s !== 'off' && s !== 0;
    })
    .map(([k]) => k)
    .sort();
};
const presets = {
  'eslint/recommended': js.configs.recommended,
  'typescript-eslint/recommended': tse.configs.recommended,
  'typescript-eslint/recommended-type-checked': tse.configs.recommendedTypeChecked,
  'typescript-eslint/strict': tse.configs.strict,
  'typescript-eslint/strict-type-checked': tse.configs.strictTypeChecked,
  'typescript-eslint/stylistic': tse.configs.stylistic,
  'typescript-eslint/stylistic-type-checked': tse.configs.stylisticTypeChecked,
  'jsdoc/recommended': jsdoc.configs['flat/recommended'],
  'jsdoc/recommended-typescript': jsdoc.configs['flat/recommended-typescript'],
  'unicorn/recommended': unicorn.configs.recommended,
};
let out = '# <preset> <rule>: rules each published preset turns on (generated by gen/gen-presets.mjs)\n';
for (const [name, cfg] of Object.entries(presets)) for (const r of on(cfg)) out += `${name} ${r}\n`;
process.stdout.write(out);
