#!/usr/bin/env node
// Writes the vendored data for unicorn/no-unnecessary-polyfills:
// src/rules/unicorn_no_unnecessary_polyfills_data.txt.
//
// Usage: node gen-polyfills-data.mjs --tools <dir with node_modules> --out <file>
//
// The data is read from the pinned packages (core-js-compat for the features, their minimum
// engine versions and the core-js entry points; browserslist with node-releases and
// caniuse-lite for the Node.js releases and browser versions the rule's queries resolve
// against). Nothing from these packages runs inside the linter.
//
// Line format (space separated):
//   #  comment
//   V  <package> <version> ...                      pinned versions
//   G  <engine> ...                                 the engine names data lines index
//   F  <feature> <engine index>=<version> ...       core-js-compat data, in its order
//   X  <feature>                                    a feature only entries name (no data)
//   L  <feature index or a-b range> ...             a distinct entry feature list
//   E  <shared prefix length> <suffix> <list index> entries, sorted, prefix-compressed
//   N  <version> ...                                Node.js releases, oldest first
//   B  <browser> <released version> ... [| <unreleased version> ...]

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(name);
  if (i < 0 || i + 1 >= args.length) throw new Error(`missing ${name}`);
  return args[i + 1];
};
const tools = path.resolve(arg('--tools'));
const out = path.resolve(arg('--out'));
const require = createRequire(path.join(tools, 'node_modules', 'index.js'));

const data = require('core-js-compat/data.json');
const entries = require('core-js-compat/entries.json');
const modules = require('core-js-compat/modules.json');
const browserslist = require('browserslist');
const version = (name) => require(`${name}/package.json`).version;

const features = Object.keys(data);
if (features.length !== modules.length || features.some((f, i) => modules[i] !== f)) {
  throw new Error('core-js-compat data and modules lists differ');
}
const index = new Map(features.map((f, i) => [f, i]));

const lines = [
  '# Generated by tests/oracle/gen/gen-polyfills-data.mjs; do not edit.',
  `V core-js-compat ${version('core-js-compat')} browserslist ${version('browserslist')} node-releases ${version('node-releases')} caniuse-lite ${version('caniuse-lite')}`,
];
const engineIndex = new Map();
for (const f of features) for (const e of Object.keys(data[f])) if (!engineIndex.has(e)) engineIndex.set(e, engineIndex.size);
lines.push(['G', ...engineIndex.keys()].join(' '));
for (const f of features) {
  const engines = Object.entries(data[f]).map(([e, v]) => `${engineIndex.get(e)}=${v}`);
  lines.push(['F', f, ...engines].join(' '));
}
for (const name of Object.keys(entries)) {
  for (const f of entries[name]) {
    if (!index.has(f)) {
      index.set(f, index.size);
      lines.push(`X ${f}`);
    }
  }
}
const lists = new Map();
const entryLines = [];
let previous = '';
for (const name of Object.keys(entries).sort()) {
  const ids = entries[name].map((f) => index.get(f));
  const parts = [];
  for (let i = 0; i < ids.length; ) {
    let j = i;
    while (j + 1 < ids.length && ids[j + 1] === ids[j] + 1) j++;
    parts.push(j - i >= 2 ? `${ids[i]}-${ids[j]}` : ids.slice(i, j + 1).join(' '));
    i = j + 1;
  }
  const key = parts.join(' ');
  if (!lists.has(key)) {
    lists.set(key, lists.size);
    lines.push(key ? `L ${key}` : 'L');
  }
  let shared = 0;
  while (shared < name.length && shared < previous.length && name[shared] === previous[shared]) shared++;
  if (/\s/.test(name)) throw new Error(`entry with whitespace: ${name}`);
  entryLines.push(`E ${shared} ${name.slice(shared)} ${lists.get(key)}`);
  previous = name;
}
lines.push(...entryLines);
lines.push(['N', ...browserslist.nodeVersions].join(' '));
// The browsers whose names core-js-compat maps to an engine it knows.
for (const b of ['android', 'and_chr', 'and_ff', 'chrome', 'edge', 'firefox', 'ie', 'ie_mob', 'ios_saf', 'op_mob', 'opera', 'safari', 'samsung']) {
  const d = browserslist.data[b];
  const released = new Set(d.released);
  const unreleased = d.versions.filter((v) => !released.has(v));
  lines.push(['B', b, ...d.released, ...(unreleased.length ? ['|', ...unreleased] : [])].join(' '));
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}: ${features.length} features, ${lists.size} lists, ${entryLines.length} entries`);
