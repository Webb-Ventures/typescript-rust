#!/usr/bin/env node
// Regenerates npm/typescript/lib/unstable/: one ES module per `typescript/unstable/*` export of
// the pinned TypeScript, re-exporting the user's real TypeScript at run time. Dependency-free.
//
//   node npm/scripts/gen-typescript-api.mjs [<typescript package dir>]
//
// Default input: bench/node_modules/typescript (the pinned reference tools; `npm ci` in bench/).
// Only export *names* are read from TypeScript (by importing its modules); nothing is copied.
// Rerun after a TypeScript bump and commit the result.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const tsDir = path.resolve(process.argv[2] || path.join(repo, 'bench/node_modules/typescript'));
const outDir = path.join(repo, 'npm/typescript/lib/unstable');

const tsPkg = JSON.parse(fs.readFileSync(path.join(tsDir, 'package.json'), 'utf8'));
if (tsPkg.name !== 'typescript') throw new Error(`${tsDir} is not the typescript package`);
const subpaths = Object.keys(tsPkg.exports).filter((s) => s.startsWith('./unstable/')).sort();

fs.rmSync(outDir, { recursive: true, force: true });
const exportsMap = {};
for (const sub of subpaths) {
  let target = tsPkg.exports[sub];
  while (target && typeof target === 'object') target = target.import || target.default;
  const mod = await import(pathToFileURL(path.join(tsDir, target)).href);
  const names = Object.keys(mod).filter((n) => n !== 'default').sort();
  const rel = sub.slice('./unstable/'.length);
  const file = path.join(outDir, `${rel}.js`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const realMjs = path.relative(path.dirname(file), path.join(repo, 'npm/typescript/lib/real.mjs')).split(path.sep).join('/');
  const lines = [
    `// Generated by npm/scripts/gen-typescript-api.mjs from typescript@${tsPkg.version}. Do not edit.`,
    `// typescript${sub.slice(1)}: re-exported from your own TypeScript (see the package README).`,
    `import { importReal } from '${realMjs.startsWith('.') ? realMjs : `./${realMjs}`}';`,
    '',
    `const m = await importReal('${sub}');`,
  ];
  if ('default' in mod) lines.push('export default m.default;');
  if (names.length) lines.push(`export const {\n${names.map((n) => `  ${n},`).join('\n')}\n} = m;`);
  fs.writeFileSync(file, lines.join('\n') + '\n');
  // Types come from the real package: resolvable when TypeScript is installed under its own name.
  fs.writeFileSync(
    path.join(outDir, `${rel}.d.ts`),
    `// Generated by npm/scripts/gen-typescript-api.mjs. Types of your own TypeScript's typescript${sub.slice(1)}.\nexport * from 'typescript${sub.slice(1)}';\n`,
  );
  exportsMap[sub] = { types: `./lib/unstable/${rel}.d.ts`, default: `./lib/unstable/${rel}.js` };
  console.log(`${sub}: ${names.length} exports`);
}

// Keep package.json's exports in step with the generated files.
const pkgFile = path.join(repo, 'npm/typescript/package.json');
const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
const kept = Object.fromEntries(Object.entries(pkg.exports).filter(([k]) => !k.startsWith('./unstable/')));
pkg.exports = { ...kept, ...exportsMap };
pkg['ts-r'].typescript = tsPkg.version;
fs.writeFileSync(pkgFile, JSON.stringify(pkg, null, 2) + '\n');
console.log(`wrote ${path.relative(repo, outDir)} and package.json exports (typescript@${tsPkg.version})`);
